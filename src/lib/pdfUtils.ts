import {
  AlignmentType,
  Document,
  LevelFormat,
  Packer,
  Paragraph,
  TextRun,
  BorderStyle,
} from 'docx';
import jsPDF from 'jspdf';

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------

function stripMarkdown(text: string): string {
  return text
    .replace(/^#{1,6}\s*/, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/_{1,2}(.+?)_{1,2}/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/^[-*•]\s*/, '')
    .replace(/Generated by Aur\.?a(?:\s*[·|].*)?/gi, '')
    .trim();
}

function toTitleCase(str: string): string {
  return str.replace(/\w\S*/g, (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
}

// ---------------------------------------------------------------------------
// Token types
// ---------------------------------------------------------------------------

type Token =
  | { kind: 'name'; text: string }
  | { kind: 'jobTitle'; text: string }
  | { kind: 'contact'; text: string }
  | { kind: 'heading'; text: string }
  | { kind: 'bullet'; text: string }
  | { kind: 'entryTitle'; text: string }
  | { kind: 'entryMeta'; text: string }
  | { kind: 'plain'; text: string };

interface Section {
  heading: string;
  tokens: Token[];
}

// ---------------------------------------------------------------------------
// Canonical section order
// ---------------------------------------------------------------------------

const SECTION_ORDER = [
  'SUMMARY', 'PERSONAL SUMMARY', 'PROFILE', 'OBJECTIVE',
  'SKILLS', 'TECHNICAL SKILLS', 'SOFT SKILLS', 'SKILLS & CORE COMPETENCIES', 'CORE COMPETENCIES', 'COMPETENCIES',
  'WORK EXPERIENCE', 'EXPERIENCE', 'EMPLOYMENT', 'EMPLOYMENT HISTORY',
  'KEY ACHIEVEMENTS', 'ACHIEVEMENTS',
  'EDUCATION', 'EDUCATION AND QUALIFICATIONS', 'QUALIFICATIONS',
  'CERTIFICATIONS AND TRAINING', 'CERTIFICATIONS', 'CERTIFICATIONS AND ACHIEVEMENTS', 'CERTIFICATES', 'TRAINING', 'COURSES', 'TRAINING AND COURSES',
  'LANGUAGES',
  'REFERENCES',
];

function sectionSortKey(heading: string): number {
  const upper = heading.toUpperCase().trim();
  for (let i = 0; i < SECTION_ORDER.length; i++) {
    if (upper === SECTION_ORDER[i] || upper.startsWith(SECTION_ORDER[i])) return i;
  }
  return SECTION_ORDER.length;
}

// ---------------------------------------------------------------------------
// Parser — understands the exact format produced by formatCVBuilderDataAsText
// ---------------------------------------------------------------------------

interface ParsedCV {
  name: string;
  jobTitle: string;
  contact: string;
  sections: Section[];
}

function parseCV(cvText: string): ParsedCV {
  const lines = cvText.split('\n').map((l) => l.trimEnd());

  let name = '';
  let jobTitle = '';
  let contact = '';
  const sections: Section[] = [];
  let current: Section | null = null;

  // The serialized format from formatCVBuilderDataAsText:
  // Line 0: fullName
  // Line 1: targetJobTitle | phone | email | city  (pipe-separated)
  // Line 2: blank
  // Line 3+: SECTION_HEADING / **bold** / plain / - bullet

  let headerPhase = 0; // 0=name, 1=contact, 2=done

  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i];
    const trimmed = raw.trim();

    if (headerPhase < 2) {
      if (!trimmed) continue;
      if (headerPhase === 0) {
        name = toTitleCase(stripMarkdown(trimmed));
        headerPhase = 1;
        continue;
      }
      if (headerPhase === 1) {
        // contact line: "targetJobTitle | phone | email | city"
        // Extract job title (first segment) and rest as contact
        const parts = trimmed.split(/\s*\|\s*/);
        if (parts.length >= 2) {
          jobTitle = stripMarkdown(parts[0]);
          contact = parts.slice(1).join(' | ');
        } else {
          contact = stripMarkdown(trimmed);
        }
        headerPhase = 2;
        continue;
      }
    }

    if (!trimmed) continue;

    // ALL-CAPS heading (no markdown prefix needed)
    const isHeading =
      /^#{1,6}\s/.test(raw) ||
      (trimmed === trimmed.toUpperCase() &&
        trimmed.length > 2 &&
        !trimmed.includes('@') &&
        !/^\d/.test(trimmed) &&
        !/^[-*•]/.test(trimmed));

    if (isHeading) {
      if (current) sections.push(current);
      current = { heading: stripMarkdown(trimmed).toUpperCase(), tokens: [] };
      continue;
    }

    if (!current) continue;

    // Bullet: starts with - * • or %
    if (/^[-*%•]\s/.test(raw) || raw.trimStart().startsWith('•')) {
      current.tokens.push({ kind: 'bullet', text: stripMarkdown(trimmed.replace(/^[-*%•]\s*/, '')) });
      continue;
    }

    // Bold entry title: **text**
    if (/^\*\*/.test(trimmed)) {
      current.tokens.push({ kind: 'entryTitle', text: stripMarkdown(trimmed) });
      continue;
    }

    // Meta line heuristic: follows an entryTitle, contains | or date pattern
    const lastToken = current.tokens[current.tokens.length - 1];
    const looksLikeMeta =
      lastToken?.kind === 'entryTitle' &&
      (trimmed.includes('|') || /\d{4}|Present/i.test(trimmed));

    if (looksLikeMeta) {
      current.tokens.push({ kind: 'entryMeta', text: stripMarkdown(trimmed) });
      continue;
    }

    current.tokens.push({ kind: 'plain', text: stripMarkdown(trimmed) });
  }

  if (current) sections.push(current);

  // Merge duplicate headings, sort by canonical order, drop empty
  const merged = new Map<string, Section>();
  for (const s of sections) {
    const key = s.heading;
    const ex = merged.get(key);
    if (ex) {
      const seen = new Set(ex.tokens.map((t) => JSON.stringify(t)));
      ex.tokens.push(...s.tokens.filter((t) => !seen.has(JSON.stringify(t))));
    } else {
      merged.set(key, { ...s });
    }
  }

  const sorted = [...merged.values()]
    .filter((s) => s.tokens.length > 0)
    .sort((a, b) => sectionSortKey(a.heading) - sectionSortKey(b.heading));

  return { name, jobTitle, contact, sections: sorted };
}

// ---------------------------------------------------------------------------
// Safe filename
// ---------------------------------------------------------------------------

function safeFilePart(value: string): string {
  return value.replace(/[^a-z0-9]/gi, '-').replace(/-+/g, '-').toLowerCase() || 'cv';
}

// ---------------------------------------------------------------------------
// ATS PDF — single column, Helvetica, left-aligned, matches reference CV
// ---------------------------------------------------------------------------

export function downloadATSReadableCVAsPDF(cvText: string, fileNameBase: string): void {
  const { name, jobTitle, contact, sections } = parseCV(cvText);

  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();   // 210mm
  const pageH = doc.internal.pageSize.getHeight();  // 297mm

  const mTop = 14;
  const mBottom = 14;
  const mLeft = 16;
  const mRight = 16;
  const contentW = pageW - mLeft - mRight;          // ~178mm
  const bottomLimit = pageH - mBottom;

  const DARK: [number, number, number] = [34, 34, 34];
  const GRAY: [number, number, number] = [68, 68, 68];

  // pt sizes converted to mm for jsPDF mm-unit doc: 1pt ≈ 0.3528mm
  // We set font sizes in pt directly via setFontSize (jsPDF accepts pt regardless of unit)
  const NAME_PT = 18;
  const TITLE_PT = 11;
  const CONTACT_PT = 9.5;
  const HEADING_PT = 10.5;
  const BODY_PT = 9.5;

  // Line heights in mm
  const NAME_LH = 7.5;
  const TITLE_LH = 5.5;
  const CONTACT_LH = 4.8;
  const HEADING_LH = 5.2;
  const BODY_LH = 4.8;   // ~1.3 line height at 9.5pt
  const BULLET_INDENT = 4; // mm hanging indent

  let y = mTop;

  const newPage = () => {
    doc.addPage();
    y = mTop;
  };

  const ensureSpace = (needed: number) => {
    if (y + needed > bottomLimit) newPage();
  };

  // ---- Name ----
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(NAME_PT);
  doc.setTextColor(...DARK);
  ensureSpace(NAME_LH);
  doc.text(name || 'Your Name', mLeft, y);
  y += NAME_LH;

  // ---- Job title ----
  if (jobTitle) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(TITLE_PT);
    doc.setTextColor(...DARK);
    ensureSpace(TITLE_LH);
    doc.text(jobTitle, mLeft, y);
    y += TITLE_LH;
  }

  // ---- Contact line ----
  if (contact) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(CONTACT_PT);
    doc.setTextColor(...DARK);
    const contactWrapped = doc.splitTextToSize(contact, contentW);
    for (const line of contactWrapped) {
      ensureSpace(CONTACT_LH);
      doc.text(line, mLeft, y);
      y += CONTACT_LH;
    }
  }

  y += 3; // small gap before sections

  // ---- Sections ----
  for (const section of sections) {
    // Keep heading + first content line together
    ensureSpace(HEADING_LH + BODY_LH + 4);

    // 10pt space above heading
    y += 3.5;

    // Section heading: UPPERCASE bold 10.5pt
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(HEADING_PT);
    doc.setTextColor(...DARK);
    doc.text(section.heading, mLeft, y);
    y += 1.5;

    // Thin rule directly under heading (~0.75pt = 0.265mm)
    doc.setDrawColor(...DARK);
    doc.setLineWidth(0.265);
    doc.line(mLeft, y, pageW - mRight, y);
    y += 1.5; // ~4pt below line

    for (const token of section.tokens) {
      if (token.kind === 'entryTitle') {
        ensureSpace(BODY_LH + 2);
        y += 1.8; // ~5pt space above entry heading
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(BODY_PT);
        doc.setTextColor(...DARK);
        const wrapped = doc.splitTextToSize(token.text, contentW);
        for (const line of wrapped) {
          ensureSpace(BODY_LH);
          doc.text(line, mLeft, y);
          y += BODY_LH;
        }
      } else if (token.kind === 'entryMeta') {
        doc.setFont('helvetica', 'italic');
        doc.setFontSize(BODY_PT);
        doc.setTextColor(...GRAY);
        const wrapped = doc.splitTextToSize(token.text, contentW);
        for (const line of wrapped) {
          ensureSpace(BODY_LH);
          doc.text(line, mLeft, y);
          y += BODY_LH;
        }
      } else if (token.kind === 'bullet') {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(BODY_PT);
        doc.setTextColor(...DARK);
        const bulletW = contentW - BULLET_INDENT;
        const wrapped = doc.splitTextToSize(token.text, bulletW);
        for (let wi = 0; wi < wrapped.length; wi++) {
          ensureSpace(BODY_LH);
          if (wi === 0) doc.text('\u2022', mLeft, y);
          doc.text(wrapped[wi], mLeft + BULLET_INDENT, y);
          y += BODY_LH;
        }
        y += 0.35; // 1pt between bullets
      } else if (token.kind === 'plain') {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(BODY_PT);
        doc.setTextColor(...DARK);
        const wrapped = doc.splitTextToSize(token.text, contentW);
        for (const line of wrapped) {
          ensureSpace(BODY_LH);
          doc.text(line, mLeft, y);
          y += BODY_LH;
        }
        y += 0.7; // ~2pt paragraph spacing after
      }
    }
  }

  doc.save(`${safeFilePart(fileNameBase)}.pdf`);
}

// ---------------------------------------------------------------------------
// ATS Word — single column, Arial, Paragraphs only, no Tables
// ---------------------------------------------------------------------------

export async function downloadATSReadableCVAsWord(cvText: string, fileNameBase: string): Promise<void> {
  const { name, jobTitle, contact, sections } = parseCV(cvText);

  // Half-points: 10pt = 20, 11pt = 22, 18pt = 36
  const BODY_SIZE = 20;   // 10pt
  const HEAD_SIZE = 22;   // 11pt
  const NAME_SIZE = 36;   // 18pt
  const TITLE_SIZE = 22;  // 11pt
  const CONTACT_SIZE = 19; // 9.5pt

  const FONT = 'Arial';
  const COLOR_DARK = '222222';
  const COLOR_GRAY = '444444';

  const headingBorder = {
    bottom: {
      style: BorderStyle.SINGLE,
      size: 6,
      color: COLOR_DARK,
      space: 1,
    },
  };

  const bulletNumbering = {
    config: [
      {
        reference: 'ats-bullet-list',
        levels: [
          {
            level: 0,
            format: LevelFormat.BULLET,
            text: '\u2022',
            alignment: AlignmentType.LEFT,
            style: {
              paragraph: {
                indent: { left: 454, hanging: 227 }, // ~4mm hanging
              },
            },
          },
        ],
      },
    ],
  };

  const children: Paragraph[] = [];

  // ---- Name ----
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: name || 'Your Name',
          bold: true,
          size: NAME_SIZE,
          font: FONT,
          color: COLOR_DARK,
        }),
      ],
      alignment: AlignmentType.LEFT,
      spacing: { after: 40 },
    }),
  );

  // ---- Job title ----
  if (jobTitle) {
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: jobTitle,
            bold: true,
            size: TITLE_SIZE,
            font: FONT,
            color: COLOR_DARK,
          }),
        ],
        alignment: AlignmentType.LEFT,
        spacing: { after: 40 },
      }),
    );
  }

  // ---- Contact line ----
  if (contact) {
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: contact,
            size: CONTACT_SIZE,
            font: FONT,
            color: COLOR_DARK,
          }),
        ],
        alignment: AlignmentType.LEFT,
        spacing: { after: 120 },
      }),
    );
  }

  // ---- Sections ----
  for (const section of sections) {
    // Section heading with bottom border underline
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: section.heading,
            bold: true,
            size: HEAD_SIZE,
            font: FONT,
            color: COLOR_DARK,
          }),
        ],
        alignment: AlignmentType.LEFT,
        spacing: { before: 200, after: 80 },
        keepNext: true,
        border: headingBorder,
      }),
    );

    for (const token of section.tokens) {
      if (token.kind === 'entryTitle') {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: token.text,
                bold: true,
                size: BODY_SIZE,
                font: FONT,
                color: COLOR_DARK,
              }),
            ],
            spacing: { before: 100, after: 40, line: 312 },
            keepNext: true,
          }),
        );
      } else if (token.kind === 'entryMeta') {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: token.text,
                italics: true,
                size: BODY_SIZE,
                font: FONT,
                color: COLOR_GRAY,
              }),
            ],
            spacing: { after: 40, line: 312 },
          }),
        );
      } else if (token.kind === 'bullet') {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: token.text,
                size: BODY_SIZE,
                font: FONT,
                color: COLOR_DARK,
              }),
            ],
            numbering: { reference: 'ats-bullet-list', level: 0 },
            spacing: { after: 20, line: 312 },
          }),
        );
      } else if (token.kind === 'plain') {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: token.text,
                size: BODY_SIZE,
                font: FONT,
                color: COLOR_DARK,
              }),
            ],
            spacing: { after: 40, line: 312 },
          }),
        );
      }
    }
  }

  // Word margins: 15mm top/bottom = 851 twips, 18mm left/right = 1021 twips
  // 1mm = 56.7 twips
  const wordDoc = new Document({
    numbering: bulletNumbering,
    styles: {
      default: {
        document: {
          run: { font: FONT, size: BODY_SIZE, color: COLOR_DARK },
        },
      },
    },
    sections: [
      {
        properties: {
          page: {
            margin: { top: 851, right: 1021, bottom: 851, left: 1021 },
          },
        },
        children,
      },
    ],
  });

  const blob = await Packer.toBlob(wordDoc);
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${safeFilePart(fileNameBase)}.docx`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
